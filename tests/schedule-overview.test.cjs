 const start=schema.indexOf('CREATE OR REPLACE FUNCTION "public"."get_judge_management_status"');
 await db.exec(schema.slice(start,schema.indexOf('$$;',start)+3));
 for(const t of ['festival_calendar','schedules','registrations','judges','schedule_judge_assignments','mark_entries','results']) await db.exec(`ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;CREATE POLICY own ON ${t} TO authenticated USING(tenant_id=current_setting('test.tenant')::uuid);`);
